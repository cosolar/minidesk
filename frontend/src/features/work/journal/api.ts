import { http } from '@/core/http/client'

export type JournalType = 'daily' | 'weekly' | 'monthly' | 'yearly'

export interface JournalVO {
  id: number | null
  journalType: JournalType
  title: string
  periodStart: string
  periodEnd: string
  templateKey: string
  content: string | null
  statsJson: string | null
  autoGenerated: boolean
  createdAt: string | null
  updatedAt: string | null
}

export interface JournalPayload {
  journalType: JournalType
  title?: string
  date?: string
  templateKey?: string
  content?: string
}

export interface PageResult<T> {
  list: T[]
  total: number
  page: number
  size: number
}

export const journalApi = {
  page(type: JournalType, page = 1, size = 50) {
    return http.get<PageResult<JournalVO>>('/journals', { type, page, size })
  },
  detail(id: number) {
    return http.get<JournalVO>(`/journals/${id}`)
  },
  draft(type: JournalType, date?: string) {
    return http.get<JournalVO>('/journals/draft', { type, date })
  },
  create(payload: JournalPayload) {
    return http.post<JournalVO>('/journals', payload)
  },
  update(id: number, payload: JournalPayload) {
    return http.put<JournalVO>(`/journals/${id}`, payload)
  },
  remove(id: number) {
    return http.delete<void>(`/journals/${id}`)
  },
}
