import { http } from '@/core/http/client'

export interface ReviewVO {
  id: string
  module: string
  reviewType: 'daily' | 'weekly' | 'monthly'
  reviewDate: string
  summary: string | null
  highlights: string | null
  issues: string | null
  nextPlan: string | null
  statsJson: string | null
  autoGenerated: boolean
}

export const reviewApi = {
  today(type: string) {
    return http.get<ReviewVO | null>('/reviews/today', { type })
  },
  list(type: string, limit = 30) {
    return http.get<ReviewVO[]>('/reviews', { type, limit })
  },
  save(payload: {
    type: string
    date: string
    module?: string
    summary?: string
    highlights?: string
    issues?: string
    nextPlan?: string
  }) {
    return http.post<ReviewVO>('/reviews', payload)
  },
  generate(payload: { type: string; date: string; module?: string }) {
    return http.post<ReviewVO>('/reviews/generate', payload)
  },
}
