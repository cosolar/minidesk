package cn.minims.desk.modules.work.journal.vo;

import cn.minims.desk.modules.work.journal.entity.JournalDO;
import java.time.LocalDate;
import java.time.LocalDateTime;

/**
 * 日志展示对象。
 */
public record JournalVO(
        Long id,
        String journalType,
        String title,
        LocalDate periodStart,
        LocalDate periodEnd,
        String templateKey,
        String content,
        String statsJson,
        boolean autoGenerated,
        LocalDateTime createdAt,
        LocalDateTime updatedAt
) {
    public static JournalVO from(JournalDO item) {
        return new JournalVO(
                item.getId(),
                item.getJournalType(),
                item.getTitle(),
                item.getPeriodStart(),
                item.getPeriodEnd(),
                item.getTemplateKey(),
                item.getContent(),
                item.getStatsJson(),
                item.getAutoGenerated() != null && item.getAutoGenerated() == 1,
                item.getCreatedAt(),
                item.getUpdatedAt());
    }

    /** 列表不返回正文，避免一次拉几百篇长文 */
    public static JournalVO brief(JournalDO item) {
        return new JournalVO(item.getId(), item.getJournalType(), item.getTitle(),
                item.getPeriodStart(), item.getPeriodEnd(), item.getTemplateKey(),
                null, item.getStatsJson(),
                item.getAutoGenerated() != null && item.getAutoGenerated() == 1,
                item.getCreatedAt(), item.getUpdatedAt());
    }
}
