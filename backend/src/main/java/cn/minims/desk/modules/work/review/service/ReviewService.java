package cn.minims.desk.modules.work.review.service;

import cn.minims.desk.common.api.ErrorCode;
import cn.minims.desk.common.exception.BizException;
import cn.minims.desk.modules.work.review.entity.ReviewDO;
import cn.minims.desk.modules.work.review.mapper.ReviewMapper;
import cn.minims.desk.modules.work.review.vo.ReviewVO;
import cn.minims.desk.modules.work.task.entity.TaskDO;
import cn.minims.desk.modules.work.task.mapper.TaskMapper;
import com.baomidou.mybatisplus.core.toolkit.Wrappers;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.util.StringUtils;

/**
 * 复盘：保存时写统计快照，历史数据不会因任务改动而漂移。
 */
@Service
public class ReviewService {

    private final ReviewMapper reviewMapper;
    private final TaskMapper taskMapper;

    public ReviewService(ReviewMapper reviewMapper, TaskMapper taskMapper) {
        this.reviewMapper = reviewMapper;
        this.taskMapper = taskMapper;
    }

    public List<ReviewVO> list(String type, String module, int limit) {
        var query = Wrappers.lambdaQuery(ReviewDO.class);
        if (StringUtils.hasText(type)) {
            query.eq(ReviewDO::getReviewType, type);
        }
        if (StringUtils.hasText(module)) {
            query.eq(ReviewDO::getModule, module);
        }
        query.orderByDesc(ReviewDO::getReviewDate).last("limit " + Math.min(Math.max(limit, 1), 100));
        return reviewMapper.selectList(query).stream().map(this::toVO).toList();
    }

    public ReviewVO find(String type, LocalDate date) {
        ReviewDO review = reviewMapper.selectOne(Wrappers.lambdaQuery(ReviewDO.class)
                .eq(ReviewDO::getReviewType, type)
                .eq(ReviewDO::getReviewDate, date)
                .last("limit 1"));
        return review == null ? null : toVO(review);
    }

    @Transactional(rollbackFor = Exception.class)
    public ReviewVO save(String type, LocalDate date, String module, String summary,
                         String highlights, String issues, String nextPlan) {
        ReviewDO review = reviewMapper.selectOne(Wrappers.lambdaQuery(ReviewDO.class)
                .eq(ReviewDO::getReviewType, type)
                .eq(ReviewDO::getReviewDate, date)
                .last("limit 1"));
        boolean isNew = review == null;
        if (isNew) {
            review = new ReviewDO();
            review.setReviewType(type);
            review.setReviewDate(date);
            review.setCreatedAt(LocalDateTime.now());
            review.setAutoGenerated(0);
        }
        review.setModule(StringUtils.hasText(module) ? module : "work");
        review.setSummary(summary);
        review.setHighlights(highlights);
        review.setIssues(issues);
        review.setNextPlan(nextPlan);
        review.setUpdatedAt(LocalDateTime.now());
        if (isNew) {
            reviewMapper.insert(review);
        } else {
            reviewMapper.updateById(review);
        }
        return toVO(review);
    }

    /**
     * 自动生成草稿：汇总该周期内完成的任务，只写 summary 与 statsJson，用户再补 highlight / issues。
     */
    @Transactional(rollbackFor = Exception.class)
    public ReviewVO generate(String type, LocalDate date, String module) {
        LocalDate end = date == null ? LocalDate.now() : date;
        LocalDate start = switch (type) {
            case "weekly" -> end.minusDays(6);
            case "monthly" -> end.withDayOfMonth(1);
            default -> end;
        };

        var query = Wrappers.lambdaQuery(TaskDO.class)
                .eq(TaskDO::getStatus, "done")
                .between(TaskDO::getDoneAt, start.atStartOfDay(), end.atTime(23, 59, 59));
        if (StringUtils.hasText(module)) {
            query.eq(TaskDO::getModule, module);
        }
        List<TaskDO> doneTasks = taskMapper.selectList(query);

        String statsJson = String.format(
                "{\"done\":%d,\"start\":\"%s\",\"end\":\"%s\"}", doneTasks.size(), start, end);
        StringBuilder summary = new StringBuilder();
        summary.append(switch (type) {
            case "weekly" -> "本周完成 " + doneTasks.size() + " 条任务";
            case "monthly" -> "本月完成 " + doneTasks.size() + " 条任务";
            default -> "今日完成 " + doneTasks.size() + " 条任务";
        });
        if (!doneTasks.isEmpty()) {
            summary.append("：");
            summary.append(String.join("、", doneTasks.stream()
                    .limit(6)
                    .map(TaskDO::getTitle)
                    .toList()));
            if (doneTasks.size() > 6) {
                summary.append(" 等");
            }
        }

        ReviewDO review = reviewMapper.selectOne(Wrappers.lambdaQuery(ReviewDO.class)
                .eq(ReviewDO::getReviewType, type)
                .eq(ReviewDO::getReviewDate, end)
                .last("limit 1"));
        boolean isNew = review == null;
        if (isNew) {
            review = new ReviewDO();
            review.setReviewType(type);
            review.setReviewDate(end);
            review.setCreatedAt(LocalDateTime.now());
            review.setModule(StringUtils.hasText(module) ? module : "work");
            review.setAutoGenerated(1);
        }
        review.setSummary(summary.toString());
        review.setStatsJson(statsJson);
        review.setUpdatedAt(LocalDateTime.now());
        if (isNew) {
            reviewMapper.insert(review);
        } else {
            reviewMapper.updateById(review);
        }
        return toVO(review);
    }

    private ReviewVO toVO(ReviewDO review) {
        return new ReviewVO(
                String.valueOf(review.getId()),
                review.getModule(),
                review.getReviewType(),
                review.getReviewDate() == null ? null : review.getReviewDate().toString(),
                review.getSummary(),
                review.getHighlights(),
                review.getIssues(),
                review.getNextPlan(),
                review.getStatsJson(),
                review.getAutoGenerated() != null && review.getAutoGenerated() == 1);
    }

    public ReviewVO require(Long id) {
        ReviewDO review = reviewMapper.selectById(id);
        if (review == null) {
            throw new BizException(ErrorCode.NOT_FOUND);
        }
        return toVO(review);
    }
}
