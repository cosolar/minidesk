package cn.minims.desk.modules.work.journal.service;

import cn.minims.desk.common.api.ErrorCode;
import cn.minims.desk.common.api.PageResult;
import cn.minims.desk.common.exception.BizException;
import cn.minims.desk.framework.tenant.TenantContext;
import cn.minims.desk.modules.work.journal.dto.JournalSaveDTO;
import cn.minims.desk.modules.work.journal.entity.JournalDO;
import cn.minims.desk.modules.work.journal.mapper.JournalMapper;
import cn.minims.desk.modules.work.journal.vo.JournalVO;
import com.baomidou.mybatisplus.core.toolkit.Wrappers;
import com.baomidou.mybatisplus.extension.plugins.pagination.Page;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.time.temporal.TemporalAdjusters;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.util.StringUtils;

/**
 * 工作日志（日 / 周 / 月 / 年）。
 *
 * <p>核心是「模板 + 自动汇总」：选周期后自动带出任务完成情况、学习时长、记账等数据，
 * 用户只需要补「感受与结论」这类机器算不出来的部分。统计快照在生成时落库，
 * 之后任务被改动也不会让历史日志的数字漂移。
 */
@Service
public class JournalService {

    private static final DateTimeFormatter DATETIME = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
    private static final Set<String> TYPES = Set.of("daily", "weekly", "monthly", "yearly");

    private final JournalMapper journalMapper;
    private final JdbcTemplate jdbcTemplate;

    public JournalService(JournalMapper journalMapper, JdbcTemplate jdbcTemplate) {
        this.journalMapper = journalMapper;
        this.jdbcTemplate = jdbcTemplate;
    }

    public PageResult<JournalVO> page(String type, long pageNo, long pageSize) {
        var query = Wrappers.lambdaQuery(JournalDO.class);
        if (StringUtils.hasText(type)) {
            query.eq(JournalDO::getJournalType, type);
        }
        query.orderByDesc(JournalDO::getPeriodStart).orderByDesc(JournalDO::getId);
        Page<JournalDO> result = journalMapper.selectPage(Page.of(pageNo, pageSize), query);
        List<JournalVO> list = result.getRecords().stream().map(JournalVO::brief).toList();
        return PageResult.of(list, result.getTotal(), pageNo, pageSize);
    }

    public JournalVO detail(Long id) {
        JournalDO item = journalMapper.selectById(id);
        if (item == null) {
            throw new BizException(ErrorCode.NOT_FOUND);
        }
        return JournalVO.from(item);
    }

    @Transactional(rollbackFor = Exception.class)
    public JournalVO create(JournalSaveDTO dto) {
        String type = normalizeType(dto.journalType());
        LocalDate base = dto.date() == null ? LocalDate.now() : dto.date();
        LocalDate[] period = periodOf(type, base);

        JournalDO item = new JournalDO();
        item.setJournalType(type);
        item.setPeriodStart(period[0]);
        item.setPeriodEnd(period[1]);
        item.setTemplateKey(StringUtils.hasText(dto.templateKey()) ? dto.templateKey() : "standard");
        item.setTitle(StringUtils.hasText(dto.title()) ? dto.title() : defaultTitle(type, period));
        item.setContent(StringUtils.hasText(dto.content())
                ? dto.content()
                : renderTemplate(type, period, collectStats(period[0], period[1]), true));
        item.setStatsJson(null);
        item.setAutoGenerated(0);
        item.setCreatedAt(LocalDateTime.now());
        item.setUpdatedAt(LocalDateTime.now());
        journalMapper.insert(item);
        return JournalVO.from(item);
    }

    @Transactional(rollbackFor = Exception.class)
    public JournalVO update(Long id, JournalSaveDTO dto) {
        JournalDO item = journalMapper.selectById(id);
        if (item == null) {
            throw new BizException(ErrorCode.NOT_FOUND);
        }
        if (StringUtils.hasText(dto.title())) {
            item.setTitle(dto.title());
        }
        if (dto.content() != null) {
            item.setContent(dto.content());
        }
        item.setUpdatedAt(LocalDateTime.now());
        journalMapper.updateById(item);
        return JournalVO.from(item);
    }

    @Transactional(rollbackFor = Exception.class)
    public void delete(Long id) {
        if (journalMapper.deleteById(id) == 0) {
            throw new BizException(ErrorCode.NOT_FOUND);
        }
    }

    /**
     * 生成草稿（不落库）：返回带真实数据的 Markdown，前端直接塞进编辑器让用户接着改。
     */
    public JournalVO draft(String type, LocalDate date) {
        String safeType = normalizeType(type);
        LocalDate base = date == null ? LocalDate.now() : date;
        LocalDate[] period = periodOf(safeType, base);
        Stats stats = collectStats(period[0], period[1]);
        return new JournalVO(null, safeType, defaultTitle(safeType, period),
                period[0], period[1], "standard",
                renderTemplate(safeType, period, stats, false),
                stats.toJson(), true, null, null);
    }

    private String normalizeType(String type) {
        return TYPES.contains(type) ? type : "daily";
    }

    private LocalDate[] periodOf(String type, LocalDate base) {
        return switch (type) {
            case "weekly" -> new LocalDate[]{
                    base.with(TemporalAdjusters.previousOrSame(DayOfWeek.MONDAY)),
                    base.with(TemporalAdjusters.nextOrSame(DayOfWeek.SUNDAY))};
            case "monthly" -> new LocalDate[]{
                    base.withDayOfMonth(1),
                    base.with(TemporalAdjusters.lastDayOfMonth())};
            case "yearly" -> new LocalDate[]{
                    LocalDate.of(base.getYear(), 1, 1),
                    LocalDate.of(base.getYear(), 12, 31)};
            default -> new LocalDate[]{base, base};
        };
    }

    private String defaultTitle(String type, LocalDate[] period) {
        return switch (type) {
            case "weekly" -> period[0] + " ~ " + period[1] + " 周报";
            case "monthly" -> period[0].getYear() + " 年 " + period[0].getMonthValue() + " 月月报";
            case "yearly" -> period[0].getYear() + " 年年报";
            default -> period[0] + " 日报";
        };
    }

    private Stats collectStats(LocalDate start, LocalDate end) {
        long userId = TenantContext.requireUserId();
        String from = start + " 00:00:00";
        String to = end + " 23:59:59";

        int done = count("select count(*) from task where user_id = ? and deleted = 0 "
                + "and status = 'done' and done_at between ? and ?", userId, from, to);
        int created = count("select count(*) from task where user_id = ? and deleted = 0 "
                + "and created_at between ? and ?", userId, from, to);
        int overdue = count("select count(*) from task where user_id = ? and deleted = 0 "
                + "and status <> 'done' and status <> 'cancelled' and due_date < ?", userId, end);
        int notes = count("select count(*) from note where user_id = ? and deleted = 0 "
                + "and created_at between ? and ?", userId, from, to);
        int journalDays = count("select count(distinct substr(created_at, 1, 10)) from note "
                + "where user_id = ? and deleted = 0 and created_at between ? and ?", userId, from, to);
        long studyMinutes = sum("select coalesce(sum(minutes), 0) from study_record "
                + "where user_id = ? and study_date between ? and ?", userId, start, end);
        long expenseCents = sum("select coalesce(sum(amount_cents), 0) from ledger "
                + "where user_id = ? and deleted = 0 and type = 'expense' and occur_date between ? and ?",
                userId, start, end);

        List<String> doneTitles = jdbcTemplate.queryForList(
                "select title from task where user_id = ? and deleted = 0 and status = 'done' "
                        + "and done_at between ? and ? order by done_at limit 30",
                String.class, userId, from, to);
        List<String> doingTitles = jdbcTemplate.queryForList(
                "select title from task where user_id = ? and deleted = 0 and status in ('todo','doing') "
                        + "and due_date between ? and ? order by due_date limit 30",
                String.class, userId, start, end);

        return new Stats(done, created, overdue, notes, journalDays, studyMinutes, expenseCents,
                doneTitles, doingTitles);
    }

    private int count(String sql, Object... args) {
        Integer value = jdbcTemplate.queryForObject(sql, Integer.class, args);
        return value == null ? 0 : value;
    }

    private long sum(String sql, Object... args) {
        Number value = jdbcTemplate.queryForObject(sql, Number.class, args);
        return value == null ? 0L : value.longValue();
    }

    private String renderTemplate(String type, LocalDate[] period, Stats stats, boolean forEdit) {
        StringBuilder sb = new StringBuilder();
        String doneList = stats.doneTitles().isEmpty()
                ? "- （本周期没有完成记录）\n"
                : "- " + String.join("\n- ", stats.doneTitles()) + "\n";
        String doingList = stats.doingTitles().isEmpty()
                ? "- （没有待办）\n"
                : "- " + String.join("\n- ", stats.doingTitles()) + "\n";

        switch (type) {
            case "weekly" -> sb.append("# ").append(defaultTitle(type, period)).append("\n\n")
                    .append("## 本周成果\n\n").append(doneList)
                    .append("\n## 关键进展\n\n- \n")
                    .append("\n## 问题与风险\n\n- \n")
                    .append("\n## 下周计划\n\n").append(doingList);
            case "monthly" -> sb.append("# ").append(defaultTitle(type, period)).append("\n\n")
                    .append("## 目标回顾\n\n- \n")
                    .append("\n## 主要产出\n\n").append(doneList)
                    .append("\n## 数据\n\n")
                    .append("- 完成任务：").append(stats.doneCount()).append(" 个\n")
                    .append("- 学习时长：").append(stats.studyMinutes() / 60).append(" 小时\n")
                    .append("- 支出：¥").append(String.format("%.2f", stats.expenseCents() / 100.0)).append("\n")
                    .append("\n## 下月计划\n\n").append(doingList);
            case "yearly" -> sb.append("# ").append(defaultTitle(type, period)).append("\n\n")
                    .append("## 年度回顾\n\n- \n")
                    .append("\n## 关键成果\n\n").append(doneList)
                    .append("\n## 能力成长\n\n- \n")
                    .append("\n## 明年计划\n\n- \n")
                    .append("\n## 数据\n\n")
                    .append("- 完成任务：").append(stats.doneCount()).append(" 个\n")
                    .append("- 学习时长：").append(stats.studyMinutes() / 60).append(" 小时\n");
            default -> sb.append("# ").append(defaultTitle(type, period)).append("\n\n")
                    .append("## 今日完成\n\n").append(doneList)
                    .append("\n## 进行中\n\n").append(doingList)
                    .append("\n## 明日计划\n\n- \n")
                    .append("\n## 备注 / 想法\n\n- \n");
        }

        if (forEdit) {
            sb.append("\n> 由模板生成，可直接修改。统计：完成 ")
                    .append(stats.doneCount()).append(" / 新建 ").append(stats.createdCount())
                    .append(" / 逾期 ").append(stats.overdueCount()).append("\n");
        }
        return sb.toString();
    }

    /** 周期统计快照 */
    private record Stats(int doneCount, int createdCount, int overdueCount, int noteCount,
                         int activeDays, long studyMinutes, long expenseCents,
                         List<String> doneTitles, List<String> doingTitles) {
        String toJson() {
            return "{\"done\":" + doneCount + ",\"created\":" + createdCount
                    + ",\"overdue\":" + overdueCount + ",\"notes\":" + noteCount
                    + ",\"activeDays\":" + activeDays + ",\"studyMinutes\":" + studyMinutes
                    + ",\"expenseCents\":" + expenseCents + "}";
        }
    }
}
