"""Generate MySQL 8 / PostgreSQL DDL from the SQLite schema.

Usage (from the repository root):
    python scripts/gen_schema.py

Requires only the Python standard library. Run this after editing
backend/src/main/resources/db/schema-sqlite.sql so all three dialects stay
in sync. This is a maintenance tool, not part of the runtime.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB_DIR = ROOT / "backend/src/main/resources/db"
SRC = DB_DIR / "schema-sqlite.sql"

text = SRC.read_text(encoding="utf-8")

table_re = re.compile(r"CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\n\);", re.S)
index_re = re.compile(
    r"CREATE (UNIQUE )?INDEX IF NOT EXISTS (\w+) ON (\w+)\(([^)]*)\);"
)

tables = {}
for m in table_re.finditer(text):
    tables[m.group(1)] = m.group(2).splitlines()

indexes = []
for m in index_re.finditer(text):
    indexes.append(
        {
            "name": m.group(2),
            "table": m.group(3),
            "cols": [c.strip() for c in m.group(4).split(",")],
            "unique": bool(m.group(1)),
        }
    )


def quote(name, dialect):
    return f"`{name}`" if dialect == "mysql" else f'"{name}"'


def map_type(token, dialect):
    base_match = re.match(r"([A-Za-z]+)", token)
    base = base_match.group(1).upper() if base_match else token.upper()
    size = token[len(base):]
    if base == "VARCHAR":
        return token
    if base == "DECIMAL":
        return "DECIMAL(18,4)" if dialect == "mysql" else "NUMERIC(18,4)"
    mapping = {
        "DATETIME": {"mysql": "DATETIME", "pg": "TIMESTAMP"},
        "DATE": {"mysql": "DATE", "pg": "DATE"},
        "TINYINT": {"mysql": "TINYINT", "pg": "SMALLINT"},
        "INTEGER": {"mysql": "INT", "pg": "INTEGER"},
        "BIGINT": {"mysql": "BIGINT", "pg": "BIGINT"},
        "TEXT": {"mysql": "TEXT", "pg": "TEXT"},
    }
    key = "mysql" if dialect == "mysql" else "pg"
    if base not in mapping:
        raise ValueError(f"Unhandled type: {token}")
    return mapping[base][key] + size


def column_lines(table, dialect):
    """Return [(definition, comment_or_None)] and the primary key column."""
    out = []
    pk = None
    for raw in tables[table]:
        if not raw.strip():
            continue
        body, sep, comment = raw.partition("--")
        if not body.strip():
            continue  # full-line comments are dropped (kept in the SQLite source)
        m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s+(.+?)\s*$", body)
        if not m:
            raise ValueError(f"Unparsed column line in {table}: {raw!r}")
        name, definition = m.group(1), m.group(2).strip()
        definition = definition.rstrip().rstrip(",").rstrip()
        tm = re.match(r"^([A-Za-z]+(?:\(\d+(?:,\d+)?\))?)\s*(.*)$", definition)
        if not tm:
            raise ValueError(f"Unparsed definition in {table}: {definition!r}")
        type_token, rest = tm.group(1), tm.group(2).strip()

        if "AUTOINCREMENT" in rest.upper() or "PRIMARY KEY" in rest.upper():
            pk = name
            if dialect == "mysql":
                defn = f"{quote(name, dialect)} BIGINT NOT NULL AUTO_INCREMENT"
            else:
                defn = f"{quote(name, dialect)} BIGINT GENERATED BY DEFAULT AS IDENTITY"
        else:
            defn = f"{quote(name, dialect)} {map_type(type_token, dialect)}"
            if rest:
                defn += " " + rest

        out.append((defn, comment.rstrip() if sep else None))
    return out, pk


def render(dialect):
    mysql = dialect == "mysql"
    lines = []
    if mysql:
        lines += [
            "-- MiniDesk schema (MySQL 8.0+)",
            "-- Generated from db/schema-sqlite.sql; table structure stays identical.",
            "-- Regenerate with: python scripts/gen_schema.py",
            "-- Idempotent: CREATE TABLE IF NOT EXISTS + inline indexes, safe to re-run.",
            "-- Init database:",
            "--   CREATE DATABASE minidesk DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
            "-- Apply:",
            "--   mysql -u root -p minidesk < schema-mysql.sql",
            "-- Runtime note: the app boots on SQLite by default. Switching to MySQL also",
            "--   requires the JDBC driver, a datasource profile and dialect-safe seed SQL",
            "--   (see docs/部署指南.md).",
        ]
    else:
        lines += [
            "-- MiniDesk schema (PostgreSQL 14+)",
            "-- Generated from db/schema-sqlite.sql; table structure stays identical.",
            "-- Regenerate with: python scripts/gen_schema.py",
            "-- Idempotent: CREATE TABLE / CREATE INDEX IF NOT EXISTS, safe to re-run.",
            "-- Apply:",
            "--   psql -d minidesk -f schema-postgresql.sql",
            "-- Runtime note: the app boots on SQLite by default. Switching to PostgreSQL",
            "--   also requires the JDBC driver, a datasource profile and dialect-safe",
            "--   seed SQL (see docs/部署指南.md).",
        ]
    lines.append("")

    for table in tables:
        cols, pk = column_lines(table, dialect)
        header = f"CREATE TABLE IF NOT EXISTS {quote(table, dialect)} ("
        body = list(cols)
        if pk:
            body.append((f"PRIMARY KEY ({quote(pk, dialect)})", None))

        if mysql:
            for idx in [i for i in indexes if i["table"] == table]:
                kind = "UNIQUE KEY" if idx["unique"] else "KEY"
                col_list = ", ".join(quote(c, dialect) for c in idx["cols"])
                body.append((f"{kind} {quote(idx['name'], dialect)} ({col_list})", None))
            tail = ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;"
        else:
            tail = ");"

        lines.append(header)
        for pos, (defn, comment) in enumerate(body):
            comma = "" if pos == len(body) - 1 else ","
            suffix = f"  --{comment}" if comment else ""
            lines.append(f"  {defn}{comma}{suffix}")
        lines.append(tail)
        lines.append("")

        if not mysql:
            for idx in [i for i in indexes if i["table"] == table]:
                kind = "CREATE UNIQUE INDEX" if idx["unique"] else "CREATE INDEX"
                col_list = ", ".join(quote(c, dialect) for c in idx["cols"])
                lines.append(
                    f"{kind} IF NOT EXISTS {quote(idx['name'], dialect)} "
                    f"ON {quote(table, dialect)} ({col_list});"
                )
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


for dialect, filename in (("mysql", "schema-mysql.sql"), ("pg", "schema-postgresql.sql")):
    target = DB_DIR / filename
    target.write_text(render(dialect), encoding="utf-8")
    print(f"wrote {target.name}: {len(tables)} tables, {len(indexes)} indexes")

# sanity checks
assert len(tables) == 59, f"unexpected table count: {len(tables)}"
assert all(i["table"] in tables for i in indexes), "index references unknown table"
for dialect, filename in (("mysql", "schema-mysql.sql"), ("pg", "schema-postgresql.sql")):
    out = (DB_DIR / filename).read_text(encoding="utf-8")
    assert len(re.findall(r"(?m)^CREATE TABLE IF NOT EXISTS", out)) == len(tables)
    assert ",, " not in out and ",,\n" not in out, "duplicate comma"
    assert "AUTOINCREMENT" not in out, "SQLite-only autoincrement leaked"
    if dialect == "mysql":
        assert out.count("ENGINE=InnoDB") == len(tables)
        assert out.count("UNIQUE KEY") + out.count("  KEY ") == len(indexes)
    else:
        assert len(re.findall(r"(?m)^CREATE (UNIQUE )?INDEX", out)) == len(indexes)
print("sanity checks passed")
